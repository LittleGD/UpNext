/**
 * 스프라이트 프레임 해석 — 보스 템플릿 id 가 있고 카탈로그에 있으면 보스 프레임,
 * 아니면 kind 프레임. 레거시 세이브(templateId 없음) 와 일반 몬스터의 경로가 같다.
 */
export function getMonsterFrames(kind: MonsterKind, templateId?: string): SpriteFrames {
  if (templateId) {
    const boss = BOSS_FRAMES[templateId];
    if (boss) return boss;
  }
  return FRAMES[kind];
}

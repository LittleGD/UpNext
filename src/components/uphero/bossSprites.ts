/**
 * Phase 6-E (Track E, 피드백 29) — 보스 전용 픽셀 스프라이트.
 *
 * `MonsterSprite` 는 kind 별 7종 실루엣만 가지고 있어 보스 24종이 전부 같은 "large"
 * 뿔 괴물로 보였다. 여기서 보스 템플릿 id → 2프레임 12×12 그리드를 따로 둔다.
 * `getMonsterFrames(kind, templateId)` 가 보스 프레임을 먼저, 없으면 kind 프레임을 돌려
 * 레거시 세이브(templateId 없음)도 그대로 그려진다.
 *
 * 아트 방향 (던전별 모티프): 실루엣 질량으로 구분한다 — 32px 에서 디테일은 사라진다.
 *   fitness: 늑대(귀+4다리, 울부짐) / 석상(각진 몸, 외눈 깜빡) / 거인(곤봉 들기)
 *   learning: 후드 저자(펼친 책, 페이지 넘김) / 현자(긴 수염+지팡이, 구슬 맥동) / 리치(두개골 관, 로브 흔들림)
 *   mindfulness: 내면의 그림자(반쪽 형상 좌우 교대) / 수도승(연화좌, 후광 맥동) / 산만함(눈 셋 덩어리, 눈 이동)
 *   nutrition: 곡물 왕(왕관 낟가리 흔들림) / 채소 거신(브로콜리 우산 떨림) / 폭식(둥근 배, 입 열고 닫기)
 *   social: 도둑 왕(망토+단검 뒤집기) / 광대(방울 셋 교대) / 외로움(속이 빈 실루엣 떠오름)
 *   productivity: 시계탑(시계판 몸통, 바늘 회전) / 시간 도적(모래시계, 모래 뒤집기) / 시간술사(시계 지팡이 기울기)
 *   wellness: 안개의 영(겹친 안개 띠 이동) / 온천의 여왕(왕관 흉상+물결 두 줄) / 무기력(넓고 낮은 구름, 반쯤 감은 눈)
 *   trending: 작은 카멜레온(말린 꼬리 토글) / 뒤틀린 유행(나선 글리치) / 카멜레온(볏 세우기)
 *
 * 규격: 2프레임 × 12행 × 12자, 문자는 '#'/'.'. bossSprites.test.ts 가 형태·유일성을
 * 강제한다. iOS `Models/BossSprites.swift` 에 그대로 복사한다 (문자열 리터럴 동일).
 */


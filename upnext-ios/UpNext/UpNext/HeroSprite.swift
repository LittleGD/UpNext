//  영웅 sprite 는 아지트의 시각 중심이라 R5 에서 실제 12×12 픽셀아트로 복원.
//
//  구조: 12×12 grid, '#' = 칠함 / '.' = 투명. 2프레임 idle 애니메이션 —
//  웹 hs-flip-1/2 keyframe (steps(2,end), animationMs=900ms) → frame1 전반 / frame2 후반.
//  iOS 는 animationMs/2 (450ms) 마다 프레임 이산 토글 (steps(2) 동치).
//
//  variant(0/1/2): 레벨별 외형 (웹 getHeroAppearanceVariant — ≥30:2, ≥10:1, else 0).
//  classType: Lv30+ 전직 시 클래스별 실루엣 (CLASS_VARIANTS). color 는 클래스 테마색.
//

import SwiftUI
import Combine

struct HeroSprite: View {
    let variant: Int
    let classType: ClassType?
    var size: CGFloat = 80
    var color: Color = HeroSprite.gbLightest
    var animationMs: Double = 900

    @State private var frame = 0

    /// GB 팔레트 (웹 upHeroPalette.ts) — 미전직 영웅 기본색.
    static let gbLightest = Color(red: 0.804, green: 0.961, blue: 0.392)  // #cdf564 = accent

    private var frames: [[String]] {
        if let c = classType { return Self.classVariants[c] ?? Self.levelVariants[0]! }
        return Self.levelVariants[min(max(variant, 0), 2)] ?? Self.levelVariants[0]!
    }

    var body: some View {
        let grid = frames[min(frame, 1)]
        Canvas { ctx, sz in
            let cell = sz.width / 12.0
            for (y, row) in grid.enumerated() {
                for (x, ch) in Array(row).enumerated() where ch == "#" {
                    // cell+0.6 으로 미세 overlap — crispEdges 픽셀 사이 헤어라인 갭 제거.
                    let rect = CGRect(x: CGFloat(x) * cell, y: CGFloat(y) * cell,
                                      width: cell + 0.6, height: cell + 0.6)
                    ctx.fill(Path(rect), with: .color(color))
                }
            }
        }
        .frame(width: size, height: size)
        // hs-flip steps(2,end) animationMs — 450ms 마다 프레임 이산 토글.
        .onReceive(Timer.publish(every: animationMs / 1000 / 2, on: .main, in: .common).autoconnect()) { _ in
            frame = 1 - frame
        }
    }

    /// 클래스 테마색 (웹 CLASS_THEME_COLOR / iOS classThemeColor).
    static func themeColor(_ c: ClassType?) -> Color {
